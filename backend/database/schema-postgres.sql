-- ==============================================================================
-- BHP Logistics Fleet Manager - PostgreSQL Database Schema
-- Target: PostgreSQL 14+ (Voroa Free PostgreSQL / Supabase / Neon / Cloud PG)
-- Idempotent, safe, and production-ready for spring.jpa.hibernate.ddl-auto=validate
-- ==============================================================================

-- 1. Users Table (Owners & Drivers)
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    phone_number VARCHAR(20),
    license_number VARCHAR(50),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    assigned_lorry_id BIGINT NULL,
    owner_id BIGINT NULL,
    password_updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_users_role ON users(role);
CREATE INDEX IF NOT EXISTS idx_users_active ON users(is_active);
CREATE INDEX IF NOT EXISTS idx_users_owner ON users(owner_id);

-- 2. Lorries Table (Commercial Freight Vehicles)
CREATE TABLE IF NOT EXISTS lorries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_number VARCHAR(20) NOT NULL UNIQUE,
    make_model VARCHAR(100) NOT NULL,
    capacity_tons NUMERIC(5, 2) NOT NULL,
    operational_status VARCHAR(25) NOT NULL DEFAULT 'AVAILABLE',
    ialert_unit_id VARCHAR(50),
    notes TEXT,
    owner_id BIGINT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_lorries_status ON lorries(operational_status);
CREATE INDEX IF NOT EXISTS idx_lorries_owner ON lorries(owner_id);

-- Circular Foreign Keys between Users and Lorries
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_users_owner'
    ) THEN
        ALTER TABLE users ADD CONSTRAINT fk_users_owner
            FOREIGN KEY (owner_id) REFERENCES users(id) ON DELETE SET NULL;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_lorries_owner'
    ) THEN
        ALTER TABLE lorries ADD CONSTRAINT fk_lorries_owner
            FOREIGN KEY (owner_id) REFERENCES users(id) ON DELETE SET NULL;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_users_assigned_lorry'
    ) THEN
        ALTER TABLE users ADD CONSTRAINT fk_users_assigned_lorry
            FOREIGN KEY (assigned_lorry_id) REFERENCES lorries(id) ON DELETE SET NULL;
    END IF;
END $$;

-- 3. Trips Table (Historical and Active Freight Trips)
CREATE TABLE IF NOT EXISTS trips (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_reference VARCHAR(50) NOT NULL UNIQUE,
    driver_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    lorry_id BIGINT NOT NULL REFERENCES lorries(id) ON DELETE RESTRICT,
    owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    origin_location VARCHAR(150) NOT NULL,
    destination_location VARCHAR(150) NOT NULL,
    trip_status VARCHAR(30) NOT NULL DEFAULT 'COMPLETED',
    trip_date DATE NOT NULL,
    start_time TIMESTAMPTZ NULL,
    end_time TIMESTAMPTZ NULL,
    distance_km NUMERIC(8, 2) NULL,
    planned_delivery_time TIMESTAMPTZ NULL,
    load_type VARCHAR(100) NULL,
    delivery_notes TEXT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_trips_driver ON trips(driver_id);
CREATE INDEX IF NOT EXISTS idx_trips_lorry ON trips(lorry_id);
CREATE INDEX IF NOT EXISTS idx_trips_owner ON trips(owner_id);
CREATE INDEX IF NOT EXISTS idx_trips_date ON trips(trip_date);
CREATE INDEX IF NOT EXISTS idx_trips_status ON trips(trip_status);

-- 4. Trip Locations Table (Real-time GPS Tracking Updates)
CREATE TABLE IF NOT EXISTS trip_locations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id BIGINT NOT NULL REFERENCES trips(id) ON DELETE CASCADE,
    lorry_id BIGINT NOT NULL REFERENCES lorries(id) ON DELETE CASCADE,
    driver_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    latitude NUMERIC(10, 7) NOT NULL,
    longitude NUMERIC(10, 7) NOT NULL,
    speed_kmh NUMERIC(6, 2) NULL,
    heading NUMERIC(5, 2) NULL,
    accuracy_meters NUMERIC(6, 2) NULL,
    client_timestamp TIMESTAMPTZ NULL,
    server_timestamp TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_trip_locations_trip_time ON trip_locations(trip_id, server_timestamp DESC);
CREATE INDEX IF NOT EXISTS idx_trip_locations_lorry_time ON trip_locations(lorry_id, server_timestamp DESC);

-- 5. Maintenance Records Table (Vehicle Service, Repairs, and Cost Ledger)
CREATE TABLE IF NOT EXISTS maintenance_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lorry_id BIGINT NOT NULL REFERENCES lorries(id) ON DELETE CASCADE,
    owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    maintenance_date DATE NOT NULL,
    service_type VARCHAR(100) NOT NULL,
    description TEXT NULL,
    cost NUMERIC(10, 2) NOT NULL,
    service_center VARCHAR(150) NULL,
    odometer_reading_km INT NULL,
    next_service_date DATE NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_maintenance_owner_date ON maintenance_records(owner_id, maintenance_date);
CREATE INDEX IF NOT EXISTS idx_maintenance_lorry_date ON maintenance_records(lorry_id, maintenance_date);

-- 6. Finance Transactions Table (Authoritative Revenue and Expense Ledger)
CREATE TABLE IF NOT EXISTS finance_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    lorry_id BIGINT NULL REFERENCES lorries(id) ON DELETE SET NULL,
    trip_id BIGINT NULL REFERENCES trips(id) ON DELETE SET NULL,
    transaction_type VARCHAR(20) NOT NULL,
    category VARCHAR(50) NOT NULL,
    description VARCHAR(255) NOT NULL,
    amount NUMERIC(12, 2) NOT NULL,
    transaction_date DATE NOT NULL,
    payment_status VARCHAR(30) NOT NULL DEFAULT 'RECEIVED',
    payment_mode VARCHAR(50) NULL,
    reference_number VARCHAR(100) NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_ft_owner_date ON finance_transactions(owner_id, transaction_date DESC);
CREATE INDEX IF NOT EXISTS idx_ft_owner_type_date ON finance_transactions(owner_id, transaction_type, transaction_date);
CREATE INDEX IF NOT EXISTS idx_ft_lorry_date ON finance_transactions(lorry_id, transaction_date);

-- 7. Trip Documents Table (E-Way Bills, Delivery Challans, Invoices)
CREATE TABLE IF NOT EXISTS trip_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id BIGINT NOT NULL REFERENCES trips(id) ON DELETE CASCADE,
    document_name VARCHAR(150) NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    stored_filename VARCHAR(255) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    file_size BIGINT NOT NULL,
    uploaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    uploaded_by_id BIGINT NOT NULL REFERENCES users(id)
);

CREATE INDEX IF NOT EXISTS idx_td_trip ON trip_documents(trip_id);
CREATE INDEX IF NOT EXISTS idx_td_uploader ON trip_documents(uploaded_by_id);

-- 8. Vehicle Documents Table (RC, Fitness, Insurance, Permits, PUC)
CREATE TABLE IF NOT EXISTS vehicle_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lorry_id BIGINT NOT NULL REFERENCES lorries(id) ON DELETE CASCADE,
    document_name VARCHAR(150) NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    stored_filename VARCHAR(255) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    file_size BIGINT NOT NULL,
    uploaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    uploaded_by_id BIGINT NOT NULL REFERENCES users(id)
);

CREATE INDEX IF NOT EXISTS idx_vd_lorry ON vehicle_documents(lorry_id);
CREATE INDEX IF NOT EXISTS idx_vd_uploader ON vehicle_documents(uploaded_by_id);


-- 9. System / Application Settings (One-Time Execution Safeguards & Metadata)
CREATE TABLE IF NOT EXISTS app_settings (
    setting_key VARCHAR(100) PRIMARY KEY,
    setting_value TEXT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
